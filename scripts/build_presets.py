def build_contracts() -> None:
    z = zipfile.ZipFile(fetch(CUAD_ZIP, CACHE / "cuad" / "data.zip"))
    data = json.loads(z.read("CUADv1.json"))["data"]
    per_doc: list[tuple[str, list[dict]]] = []
    for doc in data:
        spans = []  # (start, end, category)
        for p in doc["paragraphs"]:
            for qa in p["qas"]:
                cat = qa["id"].split("__")[-1]
                for a in qa["answers"]:
                    spans.append((a["answer_start"], a["answer_start"] + len(a["text"]), cat, a["text"]))
        clean = []
        for s, e, cat, text in spans:
            if cat not in CUAD_CATEGORIES:
                continue
            # Keep only spans no other CUAD category (of all 41) also annotates.
            if any(c2 != cat and s2 < e and s < e2 for s2, e2, c2, _ in spans):
                continue
            t = re.sub(r"\s+", " ", text).strip()
            if 120 <= len(t) <= MAX_CHARS:
                clean.append({"input": t, "reference": CUAD_CATEGORIES[cat]})
        uniq = {c["input"]: c for c in clean}
        per_doc.append((doc["title"], list(uniq.values())))

    rng = random.Random(SEED)
    rng.shuffle(per_doc)
    half = len(per_doc) // 2
    holdout_docs, train_docs = per_doc[:half], per_doc[half:]

    def stratified(docs: list, n: int, prefix: str) -> list[dict]:
        by_label: dict[str, list] = {}
        for title, items in docs:
            for k, it in enumerate(items):
                by_label.setdefault(it["reference"], []).append(
                    {"id": f"{prefix}-{re.sub(r'[^A-Za-z0-9]+', '', title)[:24]}-{k}", **it})
        for lst in by_label.values():
            rng.shuffle(lst)
        out, labels = [], sorted(by_label)
        while len(out) < n:
            for l in labels:
                if by_label[l] and len(out) < n:
                    out.append(by_label[l].pop())
        rng.shuffle(out)
        return out

    holdout = stratified(holdout_docs, N_HOLDOUT, "cuadH")
    train = stratified(train_docs, N_TRAIN, "cuadT")
    labels = list(CUAD_CATEGORIES.values())
    task = {
        "title": "Contract clause classification (32 clause types)",
        "business_story": (
            "Legal-ops and procurement teams review incoming supplier, licence and distribution contracts by tagging "
            "each clause with its type so risky terms get routed to a lawyer. Every clause of every contract goes "
            "through the classifier, so a cheaper model that tags as well as the top one cuts review cost directly."
        ),
        "instruction": (
            "You are helping a legal team review commercial contracts. Classify the contract clause below into "
            "exactly one of these clause types and reply with the label only:\n"
            + "\n".join(labels)
        ),
        "output_format": "label",
        "label_set": labels,
        "source_url": "https://www.atticusprojectai.org/cuad (github.com/TheAtticusProject/cuad, zenodo.org/records/4595826)",
        "license": "CC-BY-4.0",
        "attribution": "Hendrycks et al., 'CUAD: An Expert-Annotated NLP Dataset for Legal Contract Review', NeurIPS 2021. The Atticus Project.",
        "split_note": (
            "inputs are expert-annotated clause spans from CUAD v1 that only one CUAD category covers; split by "
            "contract (no contract appears in both train and holdout); stratified across the 32 labels."
        ),
    }
    write_task("contract-clauses", task, train, holdout, label_checker(labels))


