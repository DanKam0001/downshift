"""Regenerate the three Downshift preset tasks from their public source datasets.

    python scripts/build_presets.py            # downloads sources into presets/_cache/, writes presets/<slug>/

Every preset is built from a permissively licensed public dataset (all CC-BY-4.0):
  support-triage    Banking77 (PolyAI)                  customer-support message -> one of 77 intents
  receipt-extract   CORD v2 (NAVER Clova)               messy receipt OCR text -> JSON fields
  contract-clauses  CUAD v1 (The Atticus Project)       contract clause -> one of 32 clause types

Sampling is reproducible (fixed SEED); train and holdout never share an example (and, for CUAD, never share a
contract). Inputs are capped at MAX_CHARS characters. Stdlib + requests only.
"""
from __future__ import annotations

import csv
import io
import json
import random
import re
import zipfile
from pathlib import Path

import requests

ROOT = Path(__file__).resolve().parent.parent
PRESETS = ROOT / "presets"
CACHE = PRESETS / "_cache"
SEED = 20261027
N_TRAIN = 30
N_HOLDOUT = 40
MAX_CHARS = 1500


def fetch(url: str, dest: Path) -> Path:
    if not dest.exists():
        dest.parent.mkdir(parents=True, exist_ok=True)
        r = requests.get(url, timeout=120)
        r.raise_for_status()
        dest.write_bytes(r.content)
    return dest


def write_jsonl(path: Path, rows: list[dict]) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")


def write_task(slug: str, task: dict, train: list[dict], holdout: list[dict], checker_src: str) -> None:
    d = PRESETS / slug
    d.mkdir(parents=True, exist_ok=True)
    ids_t = {r["id"] for r in train}
    ids_h = {r["id"] for r in holdout}
    assert not ids_t & ids_h, "train/holdout overlap"
    assert not {r["input"] for r in train} & {r["input"] for r in holdout}, "duplicate input across splits"
    assert all(len(r["input"]) <= MAX_CHARS for r in train + holdout)
    task = {**task, "slug": slug, "n_train": len(train), "n_holdout": len(holdout)}
    (d / "task.json").write_text(json.dumps(task, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    write_jsonl(d / "train.jsonl", train)
    write_jsonl(d / "holdout.jsonl", holdout)
    (d / "checker.py").write_text(checker_src, encoding="utf-8", newline="\n")
    # Self-test: every reference must score 1.0 against itself.
    ns: dict = {}
    exec(compile(checker_src, str(d / "checker.py"), "exec"), ns)
    for r in train + holdout:
        s, why = ns["check"](r["reference"], r["reference"], r["input"])
        assert s == 1.0, (slug, r["id"], why)
    print(f"{slug}: {len(train)} train, {len(holdout)} holdout")


# --------------------------------------------------------------------------------------------- label checker

LABEL_CHECKER = '''"""Deterministic checker for a single-label classification task (generated by scripts/build_presets.py).

check(output, reference, input) -> (score, reason). 1.0 if the output names exactly the reference label.
Tolerant of case, whitespace, quotes, code fences, a trailing period, spaces/hyphens instead of underscores,
and a short preamble such as "Label: x". 0.0 if the output names a different label, several labels, or none.
"""
import re

LABELS = __LABELS__


def _norm(s):
    s = s.strip().lower()
    s = re.sub(r"[\\s\\-/]+", "_", s)
    return s.strip("_.\\"'`*:,;")


_NORM = {_norm(l): l for l in LABELS}


def _strip(output):
    out = output or ""
    out = re.sub(r"<think>.*?</think>", "", out, flags=re.S | re.I)
    out = re.sub(r"```[a-zA-Z]*", "", out).replace("```", "")
    return out.strip()


def extract(output):
    out = _strip(output)
    if _norm(out) in _NORM:
        return _NORM[_norm(out)]
    # Also try the last non-empty line, e.g. "Intent:\\ncard_arrival".
    lines = [l for l in out.splitlines() if l.strip()]
    if lines:
        last = re.sub(r"^[a-z _]*(label|intent|category|answer|type)\\s*[:=]\\s*", "", lines[-1].strip(), flags=re.I)
        if _norm(last) in _NORM:
            return _NORM[_norm(last)]
    flat = "_" + re.sub(r"[^a-z0-9]+", "_", out.lower()) + "_"
    found = set()
    for n, l in _NORM.items():
        if "_" + n + "_" in flat:
            found.add(l)
    # Drop labels that are only found as part of a longer found label.
    found = {l for l in found if not any(l != o and _norm(l) in _norm(o) for o in found)}
    if len(found) == 1:
        return found.pop()
    return None if not found else sorted(found)


def check(output, reference, input=""):
    got = extract(output)
    if got is None:
        return 0.0, "no valid label in output: " + repr(_strip(output)[:80])
    if isinstance(got, list):
        return 0.0, "several labels in output: " + ", ".join(got[:4])
    if got == reference:
        return 1.0, "correct: " + got
    return 0.0, "wrong label: got " + got + ", expected " + reference
'''


def label_checker(labels: list[str]) -> str:
    return LABEL_CHECKER.replace("__LABELS__", json.dumps(labels, indent=4))


# --------------------------------------------------------------------------------------------- 1. Banking77

BANKING_BASE = "https://raw.githubusercontent.com/PolyAI-LDN/task-specific-datasets/master/banking_data/"


def build_banking() -> None:
    def load(name: str) -> list[dict]:
        p = fetch(BANKING_BASE + name, CACHE / "banking77" / name)
        return list(csv.DictReader(io.StringIO(p.read_text(encoding="utf-8"))))

    train_src, test_src = load("train.csv"), load("test.csv")
    labels = json.loads(fetch(BANKING_BASE + "categories.json", CACHE / "banking77" / "categories.json").read_text())
    rng = random.Random(SEED)

    def sample(rows: list[dict], n: int, prefix: str) -> list[dict]:
        idx = list(range(len(rows)))
        rng.shuffle(idx)
        out = []
        for i in idx[:n]:
            out.append({"id": f"{prefix}-{i:05d}", "input": rows[i]["text"].strip(), "reference": rows[i]["category"]})
        return out

    holdout = sample(test_src, N_HOLDOUT, "b77test")
    train = sample(train_src, N_TRAIN, "b77train")
    task = {
        "title": "Support ticket triage (77 banking intents)",
        "business_story": (
            "A retail bank or fintech routes every incoming chat and email to the right queue or self-service answer "
            "by intent, for every customer message, all day. At that volume each call is cheap but the bill is not, "
            "so the smallest model that routes as well as the biggest one is the one you want."
        ),
        "instruction": (
            "You are triaging customer messages sent to a bank's support team. Classify the customer's message into "
            "exactly one of the intent labels below. Reply with the label only, exactly as written.\n\nLabels:\n"
            + "\n".join(labels)
        ),
        "output_format": "label",
        "label_set": labels,
        "source_url": "https://github.com/PolyAI-LDN/task-specific-datasets (Banking77; also huggingface.co/datasets/PolyAI/banking77)",
        "license": "CC-BY-4.0",
        "attribution": "Casanueva et al., 'Efficient Intent Detection with Dual Sentence Encoders', NLP4ConvAI 2020. PolyAI.",
        "split_note": "holdout sampled from the official test split, train from the official train split",
    }
    write_task("support-triage", task, train, holdout, label_checker(labels))


# --------------------------------------------------------------------------------------------- 2. CORD receipts

CORD_ROWS = "https://datasets-server.huggingface.co/rows?dataset=naver-clova-ix/cord-v2&config=default&split={split}&offset={off}&length=100"

RECEIPT_FIELDS = ["subtotal", "discount", "service_charge", "tax", "total", "cash_paid", "change"]

RECEIPT_CHECKER = '''"""Deterministic checker for receipt extraction to JSON (generated by scripts/build_presets.py).

check(output, reference, input) -> (score, reason). Partial credit: the score is the mean over 8 fields,
the 7 money fields (exact integer match, null must be null) plus "items" (F1 over line items, where an item
matches when its price is equal and its name is similar). Tolerant of code fences, prose around the JSON,
key order and case, and amounts written as "25.000", "Rp 25,000" or 25000.
"""
import difflib
import json
import re

MONEY = __FIELDS__


def parse_amount(v):
    if v is None or isinstance(v, bool):
        return None
    if isinstance(v, (int, float)):
        return int(round(abs(v)))
    s = str(v).strip().lower()
    if s in ("", "null", "none", "n/a", "-"):
        return None
    s = re.sub(r"[.,]00$", "", s)
    digits = re.sub(r"[^0-9]", "", s)
    return int(digits) if digits else None


def _json_from(output):
    out = re.sub(r"<think>.*?</think>", "", output or "", flags=re.S | re.I)
    m = re.search(r"```(?:json)?\\s*(.*?)```", out, flags=re.S)
    if m:
        out = m.group(1)
    start = out.find("{")
    if start < 0:
        return None
    depth = 0
    for i in range(start, len(out)):
        if out[i] == "{":
            depth += 1
        elif out[i] == "}":
            depth -= 1
            if depth == 0:
                try:
                    return json.loads(out[start:i + 1])
                except ValueError:
                    return None
    return None


def _lower_keys(d):
    return {str(k).strip().lower(): v for k, v in d.items()} if isinstance(d, dict) else {}


def _name(s):
    return re.sub(r"[^a-z0-9]+", " ", str(s or "").lower()).strip()


def _items_f1(got, ref):
    got = [_lower_keys(x) for x in (got or []) if isinstance(x, dict)]
    ref = [_lower_keys(x) for x in (ref or [])]
    if not ref and not got:
        return 1.0
    if not ref or not got:
        return 0.0
    used, tp = set(), 0
    for r in ref:
        rp, rn = parse_amount(r.get("price")), _name(r.get("name"))
        best, best_j = 0.0, None
        for j, g in enumerate(got):
            if j in used or parse_amount(g.get("price")) != rp:
                continue
            sim = difflib.SequenceMatcher(None, rn, _name(g.get("name"))).ratio()
            if sim > best:
                best, best_j = sim, j
        if best_j is not None and best >= 0.6:
            used.add(best_j)
            tp += 1
    if tp == 0:
        return 0.0
    p, r = tp / len(got), tp / len(ref)
    return 2 * p * r / (p + r)


def check(output, reference, input=""):
    ref = json.loads(reference) if isinstance(reference, str) else reference
    got = _json_from(output)
    if not isinstance(got, dict):
        return 0.0, "no JSON object in output"
    got = _lower_keys(got)
    scores, misses = [], []
    for f in MONEY:
        ok = parse_amount(got.get(f)) == parse_amount(ref.get(f))
        scores.append(1.0 if ok else 0.0)
        if not ok:
            misses.append(f"{f}: got {got.get(f)!r}, expected {ref.get(f)!r}")
    f1 = _items_f1(got.get("items"), ref.get("items"))
    scores.append(f1)
    if f1 < 1:
        misses.append(f"items F1 {f1:.2f}")
    score = sum(scores) / len(scores)
    return round(score, 4), ("all fields correct" if not misses else "; ".join(misses))
'''


def _cord_text(gt: dict) -> str:
    rows: dict[int, list] = {}
    for line in gt["valid_line"]:
        for w in line["words"]:
            q = w["quad"]
            rows.setdefault(w["row_id"], []).append((q["x1"], (q["y1"] + q["y3"]) / 2, w["text"]))
    ordered = sorted(rows.values(), key=lambda ws: sum(w[1] for w in ws) / len(ws))
    return "\n".join(" ".join(t for _, _, t in sorted(ws)) for ws in ordered)


def _strict_amount(v) -> int | None:
    """Reference-side parse; raises on anything we would not trust as an integer rupiah amount."""
    if v is None:
        return None
    s = re.sub(r"^(rp\.?|@)\s*", "", str(v).strip().lower())
    s = s.strip("()")
    s = re.sub(r"[.,]00$", "", s).lstrip("-")
    if not re.fullmatch(r"\d{1,3}([.,]\d{3})*|\d+", s):
        raise ValueError(v)
    return int(re.sub(r"[.,]", "", s))


def _cord_reference(gp: dict) -> dict | None:
    try:
        menu = gp.get("menu", [])
        menu = [menu] if isinstance(menu, dict) else menu
        items = []
        for m in menu:
            nm = m.get("nm")
            if isinstance(nm, list) or not nm:
                return None
            price = m.get("price") or m.get("itemsubtotal")
            if isinstance(price, list) or price is None:
                return None  # keep only receipts whose every line item has a printed line total
            cnt = m.get("cnt")
            q = None
            if isinstance(cnt, str):
                mm = re.search(r"\d+", cnt)
                q = int(mm.group()) if mm else None
            items.append({"name": nm.strip(), "quantity": q, "price": _strict_amount(price)})
        st, tot = gp.get("sub_total", {}) or {}, gp.get("total", {}) or {}
        if isinstance(st, list) or isinstance(tot, list):
            return None
        vals = {
            "subtotal": st.get("subtotal_price"),
            "discount": st.get("discount_price"),
            "service_charge": st.get("service_price"),
            "tax": st.get("tax_price"),
            "total": tot.get("total_price"),
            "cash_paid": tot.get("cashprice"),
            "change": tot.get("changeprice"),
        }
        if any(isinstance(v, list) for v in vals.values()):
            return None
        ref = {"items": items}
        for k, v in vals.items():
            ref[k] = _strict_amount(v)
        if ref["total"] is None:
            return None
        return ref
    except ValueError:
        return None


def build_receipts() -> None:
    def load(split: str, offsets: list[int]) -> list[dict]:
        out = []
        for off in offsets:
            p = fetch(CORD_ROWS.format(split=split, off=off), CACHE / "cord-v2" / f"{split}_{off}.json")
            for r in json.loads(p.read_text(encoding="utf-8"))["rows"]:
                out.append({"row_idx": r["row_idx"], "gt": json.loads(r["row"]["ground_truth"])})
        return out

    def prepare(rows: list[dict], prefix: str) -> list[dict]:
        out = []
        for r in rows:
            ref = _cord_reference(r["gt"]["gt_parse"])
            text = _cord_text(r["gt"])
            if ref is None or len(text) > MAX_CHARS or len(text) < 40:
                continue
            out.append({"id": f"{prefix}-{r['row_idx']:04d}", "input": text,
                        "reference": json.dumps(ref, ensure_ascii=False)})
        return out

    rng = random.Random(SEED)
    holdout_pool = prepare(load("test", [0]), "cordtest")
    train_pool = prepare(load("validation", [0]), "cordval")
    rng.shuffle(holdout_pool)
    rng.shuffle(train_pool)
    holdout = holdout_pool[:N_HOLDOUT]
    # CORD's validation and test splits share a few identical receipts; never let one leak into train.
    seen = {r["input"] for r in holdout_pool}
    train = [r for r in train_pool if r["input"] not in seen][:N_TRAIN]
    schema = {
        "type": "object",
        "properties": {
            "items": {"type": "array", "items": {"type": "object", "properties": {
                "name": {"type": "string"}, "quantity": {"type": ["integer", "null"]},
                "price": {"type": ["integer", "null"]}}, "required": ["name", "quantity", "price"]}},
            **{f: {"type": ["integer", "null"]} for f in RECEIPT_FIELDS},
        },
        "required": ["items", *RECEIPT_FIELDS],
    }
    task = {
        "title": "Receipt OCR to structured JSON",
        "business_story": (
            "Expense-management and bookkeeping tools turn photographed receipts into ledger entries; after OCR the "
            "text is jumbled, and a model has to pull out the line items and totals for every receipt a customer "
            "uploads. It runs once per document at high volume, so the per-call price decides the margin."
        ),
        "instruction": (
            "The text below is the OCR output of a shop or restaurant receipt from Indonesia (amounts in rupiah). "
            "Extract the following as a JSON object and reply with the JSON only:\n"
            '- "items": the purchased line items, each {"name": string as printed, "quantity": integer or null, '
            '"price": the line total as printed, integer}. Do not list sub-items or modifiers printed under an item.\n'
            '- "subtotal", "discount", "service_charge", "tax", "total", "cash_paid", "change": integers, or null if '
            "the receipt does not print that amount.\n"
            "Write every amount as a plain integer with no currency or separators (\"Rp 25.000\" -> 25000). "
            "Discounts are positive numbers."
        ),
        "output_format": "json",
        "json_schema": schema,
        "source_url": "https://huggingface.co/datasets/naver-clova-ix/cord-v2 (github.com/clovaai/cord)",
        "license": "CC-BY-4.0",
        "attribution": "Park et al., 'CORD: A Consolidated Receipt Dataset for Post-OCR Parsing', 2019. NAVER Clova.",
        "split_note": (
            "input is the dataset's own OCR words regrouped into lines by row_id; reference built from gt_parse. "
            "Receipts with ambiguous amounts, an item without a line total, or nested multi-value fields were dropped. Holdout from the test split, "
            "train from the validation split (the rows API does not serve the train split)."
        ),
    }
    write_task("receipt-extract", task, train, holdout,
               RECEIPT_CHECKER.replace("__FIELDS__", json.dumps(RECEIPT_FIELDS)))


